#!/usr/bin/env python3
"""Turn the KT 1121 boarding-pass merge workbook into pass tokens.

    python3 scripts/import_passes.py path/to/KT1121_boarding_pass_merge.xlsx

Reads the PASSENGERS and PRINT MERGE tabs and writes three files to private/
(git-ignored: they hold guests' names and the links to their passes):

  pass-tokens.csv            zola_guest_id -> token. The source of truth for
                             tokens: re-running keeps every existing token, so
                             a printed QR never stops working. Back it up.
  passes.sql                 upserts every attending guest into public.passes.
                             Paste into the Supabase SQL editor, or run with psql.
  print-merge-with-qr.csv    the PRINT MERGE tab plus a qr_url column, for the
                             print shop: the QR on the stub ("ADD TO WALLET").

Only guests with RSVP = Yes are included. A guest without a Zola guest ID is
an error, because the token is keyed on it.

Needs: pip install openpyxl
"""
import csv
import secrets
import sys
from pathlib import Path

try:
    import openpyxl
except ImportError:
    sys.exit("Needs openpyxl: pip install openpyxl")

SITE = "https://wedding.peitzman.net"
OUT = Path(__file__).resolve().parent.parent / "private"


def rows(ws):
    it = ws.iter_rows(values_only=True)
    header = [str(h).strip() if h is not None else "" for h in next(it)]
    for r in it:
        if any(v is not None for v in r):
            yield dict(zip(header, r))


def col(row, *names):
    """First matching column, tolerant of the workbook's long header names."""
    for name in names:
        for key, value in row.items():
            if key.upper().startswith(name.upper()):
                return value
    return None


def text(v):
    return None if v is None or str(v).strip() == "" else str(v).strip()


def sql(v):
    if v is None:
        return "null"
    if isinstance(v, int):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def main(path):
    wb = openpyxl.load_workbook(path, data_only=True)
    passengers = [r for r in rows(wb["PASSENGERS"]) if str(col(r, "RSVP") or "").strip().lower() == "yes"]

    OUT.mkdir(exist_ok=True)
    tokens_file = OUT / "pass-tokens.csv"
    tokens = {}
    if tokens_file.exists():
        with tokens_file.open() as f:
            tokens = {r["zola_guest_id"]: r["token"] for r in csv.DictReader(f)}

    problems, records = [], []
    for r in passengers:
        zola = text(col(r, "ZOLA GUEST ID"))
        name = f"{text(col(r, 'FIRST NAME')) or ''} {text(col(r, 'LAST NAME')) or ''}".strip()
        if not zola:
            problems.append(f"no Zola guest ID: {name or col(r, 'PASS NAME')}")
            continue
        if str(col(r, "CHECK") or "").strip().upper() != "OK":
            problems.append(f"CHECK is not OK: {name}")
        token = tokens.setdefault(zola, secrets.token_urlsafe(12))  # 16 URL-safe characters
        records.append({
            "token": token, "zola_guest_id": zola,
            "first_name": text(col(r, "FIRST NAME")) or "", "last_name": text(col(r, "LAST NAME")) or "",
            "table_number": int(col(r, "TABLE NO")) if col(r, "TABLE NO") is not None else None,
            "side": text(col(r, "SIDE")), "household": text(col(r, "HOUSEHOLD")),
            "pass_name": text(col(r, "PASS NAME")), "strip_name": text(col(r, "STRIP NAME")),
            "gate": text(col(r, "GATE")), "destination_city": text(col(r, "DESTINATION")),
            "destination_code": text(col(r, "CODE")), "cabin": text(col(r, "CLASS")),
            "seat": text(col(r, "SEAT")), "seq": int(col(r, "SEQ")) if col(r, "SEQ") is not None else None,
            "pnr": text(col(r, "PNR")), "ssr_remarks": text(col(r, "SSR")), "bcbp": text(col(r, "BCBP")),
        })

    seen = {}
    for rec in records:
        if rec["bcbp"] in seen:
            problems.append(f"duplicate BCBP string: {rec['pass_name']} and {seen[rec['bcbp']]}")
        seen[rec["bcbp"]] = rec["pass_name"]

    with tokens_file.open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["zola_guest_id", "token"])
        for zola, token in sorted(tokens.items()):
            w.writerow([zola, token])

    cols = list(records[0].keys()) if records else []
    with (OUT / "passes.sql").open("w") as f:
        f.write("-- Generated by scripts/import_passes.py. Contains guest names: do not commit.\n")
        f.write(f"insert into public.passes ({', '.join(cols)}) values\n")
        f.write(",\n".join("  (" + ", ".join(sql(rec[c]) for c in cols) + ")" for rec in records))
        updates = ", ".join(f"{c} = excluded.{c}" for c in cols if c not in ("token", "zola_guest_id"))
        f.write(f"\non conflict (token) do update set {updates}, updated_at = now();\n")

    by_bcbp = {rec["bcbp"]: rec["token"] for rec in records}
    merge = list(rows(wb["PRINT MERGE"]))
    missing = 0
    with (OUT / "print-merge-with-qr.csv").open("w", newline="") as f:
        fields = [k for k in merge[0].keys() if k] + ["qr_url"] if merge else []
        w = csv.DictWriter(f, fieldnames=fields, extrasaction="ignore")
        w.writeheader()
        for r in merge:
            if not text(r.get("bcbp_string")):
                continue  # blank template rows and notes
            token = by_bcbp.get(text(r.get("bcbp_string")))
            if not token:
                missing += 1
                continue
            w.writerow({**r, "qr_url": f"{SITE}/p/?pass={token}"})
    if missing:
        problems.append(f"{missing} PRINT MERGE rows had no attending guest with the same BCBP string (left out)")

    print(f"{len(records)} attending guests -> {OUT}/")
    print("  pass-tokens.csv, passes.sql, print-merge-with-qr.csv")
    for p in problems:
        print("  check:", p)


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
